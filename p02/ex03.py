# 평균 나이 구하기
# 연산의 우선순위
print((50 + 45 + 33 + 39 + 29 + 30) / 6)
# 37.666666666666664
print((50 + 45 + 33 + 39 + 29 + 30) // 6)
# 37
# 소숫점 첫째 자리까지 표시
print(round((50 + 45 + 33 + 39 + 29 + 30) / 6, 2))
# 37.67

