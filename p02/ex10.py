# 부가가치세 출력 프로그램 만들기
# 연산자
print(5000 * 1.1) # 5500.0
print(5000 / 1.1) # 4545.454545454545
print(8000 / 1.1) # 7272.727272727272
# round(숫자, 자릿수)
# 소수 첫째자리까지 표시
print(round(8000 / 1.1, 1)) # 7272.7
print(round(8000 / 1.1)) # 7273

print(8000 - 7273) # 727
print(round(8000 * (1 / 11))) # 727

